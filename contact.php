  var validations = <?php require_once 'config.php';echo json_encode($validations); ?>;

function va() {
  var name = document.getElementById('name').value.trim();
  var email = document.getElementById('email').value.trim();
  var mobile = document.getElementById('mobile').value.trim();
  var interstedin = document.getElementById('desc').value.trim();
  var captcha = document.getElementsByName('captcha')[0].value.trim();
  
  // Validate Name
  if (name == "") {
      alert("Please enter your name.");
      document.getElementById('name').focus();
      return false;
  }
  if (name.length > validations.name.length) {
      alert("Name cannot exceed " + validations.name.length + " characters.");
      document.getElementById('name').focus();
      return false;
  }
  if (!name.match(validations.name.pattern)) {
      alert("Please enter a valid name.");
      document.getElementById('name').focus();
      return false;
  }
  
  // Validate Email
  if (email == "") {
      alert("Please enter your email.");
      document.getElementById('email').focus();
      return false;
  }
  if (email.length > validations.email.length) {
      alert("Email cannot exceed " + validations.email.length + " characters.");
      document.getElementById('email').focus();
      return false;
  }
  if (!email.match(validations.email.pattern)) {
      alert("Please enter a valid email address.");
      document.getElementById('email').focus();
      return false;
  }
  
  if (mobile == "") {
      alert("Please enter your mobile number.");
      document.getElementById('mobile').focus();
      return false;
  }
  if (mobile.length != validations.mobile.length) {
      alert("Mobile number must be " + validations.mobile.length + " digits long.");
      document.getElementById('mobile').focus();
      return false;
  }
  if (!mobile.match(validations.mobile.pattern)) {
      alert("Please enter a valid 10-digit mobile number.");
      document.getElementById('mobile').focus();
      return false;
  }
  if (interstedin.length > validations.interstedin.length) {
      alert("Interested In cannot exceed " + validations.interstedin.length + " characters.");
      document.getElementById('desc').focus();
      return false;
  }
  if (!interstedin.match(validations.interstedin.pattern)) {
      alert("Please enter a valid description.");
      document.getElementById('desc').focus();
      return false;
  }
  
  if (captcha == "") {
      alert("Please enter the captcha code.");
      document.getElementsByName('captcha')[0].focus();
      return false;
  }
  var form = document.getElementById('form');
  var formData = new FormData(form);
  var xhr = new XMLHttpRequest();
  xhr.open('POST', form.action);
  
  xhr.onload = function() {
      if (xhr.status === 200) {
          alert(xhr.responseText);
          
      } else {
          // alert('Failed to submit form. Error ' + xhr.responseText);
          alert('Mail Sent Succesfully.');
      }
      window.location.reload();
  };

  xhr.onerror = function() {
      var errorMessage = "An error occurred. Please try again later.";
      if (xhr.responseText) {
          errorMessage = xhr.responseText;
      }
      alert(errorMessage);
  };

  xhr.send(formData);
  return false;
}   
